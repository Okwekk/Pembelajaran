reader.addEventListener('click', event => {
  const button = event.target.closest('[data-answer]');
  if (!button || !currentArticle) return;
  const answer = Number(button.dataset.answer);
  const correct = answer === currentArticle.quiz.answer;
  reader.querySelectorAll('[data-answer]').forEach(option => {
    option.setAttribute('aria-pressed', String(option === button));
    option.classList.remove('is-wrong');
  });
  button.classList.toggle('is-wrong', !correct);
  const feedback = document.querySelector('#quiz-feedback');
  feedback.textContent = `${correct ? '✓ Tepat! ' : 'Belum tepat. '}${currentArticle.quiz.feedback[answer]}${correct ? '' : ' Kamu bisa mencoba lagi.'}`;
  feedback.classList.toggle('is-wrong', !correct);
  feedback.hidden = false;
  updateReadingProgress();
});
