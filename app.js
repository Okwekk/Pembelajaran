function updateInflation() {
  const rate = Number(inflation.value);
  const difference = 100000 * rate / 100;
  document.querySelector('#inflation-value').textContent = `${rate}%`;
  document.querySelector('#basket-cost').textContent = rupiah(100000 + difference);
  const explanation = document.querySelector('#simulation-result');
  if (rate > 0) explanation.innerHTML = `Untuk barang yang sama, kamu perlu tambahan <strong>${rupiah(difference)}</strong>. Jika uangmu tetap, jumlah barang yang bisa dibeli berkurang.`;
  else if (rate < 0) explanation.innerHTML = `Keranjang yang sama lebih murah <strong>${rupiah(-difference)}</strong>. Ini contoh deflasi: dengan uang tetap, daya belimu pada keranjang ini meningkat.`;
  else explanation.innerHTML = `Biaya keranjang tetap <strong>${rupiah(100000)}</strong>. Dalam contoh ini, tidak ada perubahan harga atau daya beli jika uangmu tetap.`;
}
